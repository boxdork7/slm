// Prettier 代码格式化配置文件
// @see https://prettier.io/docs/en/options

module.exports = {
  // ================================
  // 引号和字符串配置
  // ================================

  // 使用单引号而不是双引号
  // 示例：'hello' 而不是 "hello"
  // 减少视觉噪音，在 JavaScript 中更常见
  singleQuote: true,

  // ================================
  // 行宽和换行配置
  // ================================

  // 单行最大字符数，超过会自动换行
  // 100 字符是现代编辑器的较好平衡点
  // 相比默认的 80 字符，能减少不必要的换行
  printWidth: 100,

  // 每行结束是否添加分号
  // false = 不添加分号（依赖 ASI - 自动分号插入）
  // 现代 JavaScript 趋势，代码更简洁
  semi: false,

  // 行尾换行符处理方式
  // 'auto' = 让 Prettier 自动检测并保持现有文件的换行符
  // 避免跨平台开发时的换行符冲突问题
  endOfLine: 'auto',

  // ================================
  // 缩进配置
  // ================================

  // 缩进宽度（空格数）
  // 2 个空格是前端开发的主流选择
  tabWidth: 2,

  // 是否使用制表符（Tab）进行缩进
  // false = 使用空格缩进，更一致跨编辑器显示
  useTabs: false,

  // ================================
  // 对象和数组格式化
  // ================================

  // 尾随逗号配置
  // 'all' = 在所有可能的地方添加尾随逗号
  // 好处：版本控制时 diff 更清晰，添加新项时不需要修改上一行
  // 示例：{ a: 1, b: 2, } 和 [1, 2, 3,]
  trailingComma: 'all',

  // ================================
  // HTML/模板相关配置
  // ================================

  // HTML 空白字符敏感度
  // 'ignore' = 忽略 HTML 中的空白字符格式化
  // 避免在 Vue 模板或 HTML 中出现意外的空白字符变化
  // 对于组件库开发特别重要
  htmlWhitespaceSensitivity: 'ignore',

  // ================================
  // 特定文件类型覆盖配置
  // ================================

  overrides: [
    {
      // 针对 JSON 文件的特殊配置
      files: '*.json',
      options: {
        // JSON 文件不使用尾随逗号
        // JSON 标准不支持尾随逗号，会导致解析错误
        trailingComma: 'none',
      },
    },
  ],
}
